/** The check of the Minimum CI the sync waits for. */
const CI_OK = 'ci-ok';

/**
 * Publishes the release a merged Release PR carries, when the pushed commit
 * is the merge of one; otherwise does nothing. In order: verify the Release
 * PR, tag the merge commit (as the Publish App), publish with retries (skipped
 * when every package is already on the registry, so that a run started again
 * after the registry took them goes on to the verification), verify every
 * package and dist-tag on the registry, bring the release back to
 * `dev` (current line only), and open the rotation Issue after the first
 * stable release of a major. Any failure stops the rest.
 * @param options - Flags
 * @param options.dryRun - Decide and report without writing
 * @example
 * await publishCommand({ dryRun: false });
 */
export async function publishCommand(options: {
	readonly dryRun: boolean;
}): Promise<void> {
	const git = localGit();
	const gh = github('GITHUB_TOKEN');
	const publishGh = github('PUBLISH_APP_TOKEN');
	const branch = requireEnv('GITHUB_REF_NAME');
	const sha = git.sha('HEAD');
	const { lines } = classifiedLines(git, new Date());
	const line = lines.find(({ publishBranch }) => publishBranch === branch);
	if (line === undefined) {
		await summary(`${branch} is not a publish branch`);
		return;
	}

	const pulls = await gh.rest<
		{
			number: number;
			merge_commit_sha: string | null;
			merged_at: string | null;
			user: { login: string };
			body: string | null;
			labels: { name: string }[];
			head: { sha: string };
		}[]
	>('GET', `/repos/{repo}/commits/${sha}/pulls`);
	const pr = pulls.find(
		(candidate) =>
			candidate.merge_commit_sha === sha &&
			candidate.merged_at !== null &&
			candidate.labels.some(({ name }) => name === RELEASE_LABEL) &&
			(candidate.body ?? '').includes(lineMarker(line.branch)),
	);
	if (pr === undefined) {
		await summary(`${sha} is not the merge of a Release PR; nothing to publish`);
		return;
	}
	const headCommit = await gh.rest<{ author: { login: string } | null }>(
		'GET',
		`/repos/{repo}/commits/${pr.head.sha}`,
	);
	const origin = releasePrOrigin(
		{
			author: pr.user.login,
			commits: [{ author: headCommit.author?.login ?? null, verified: true }],
			body: pr.body ?? '',
			labels: pr.labels.map(({ name }) => name),
		},
		`${requireEnv('RELEASE_APP_SLUG')}[bot]`,
	);
	if (!origin.ok) {
		throw new Error(
			`#${pr.number} was not generated by the Release App: ${origin.reasons.join('; ')}`,
		);
	}
	const checks = await gh.rest<{
		check_runs: { name: string; conclusion: string | null }[];
	}>('GET', `/repos/{repo}/commits/${pr.head.sha}/check-runs?check_name=${VERIFY_CHECK}`);
	if (!checks.check_runs.some(({ conclusion }) => conclusion === 'success')) {
		throw new Error(`#${pr.number} has no successful ${VERIFY_CHECK} check`);
	}

	const mode = publishModeAt(git, 'HEAD');
	const packages = publicPackages(git, 'HEAD');
	const stableTagsBefore = git.tags('HEAD').filter((tag) => /^v\d+\.\d+\.\d+$/.test(tag));
	const unpublished = await unpublishedPackages(packages);
	const version = versionAt(git, 'HEAD');
	// Nothing to publish: a run that starts again after the registry took the
	// packages goes on with the verification instead of publishing over them.
	// The dist-tag is still decided and checked, for every package, because the
	// earlier run may have died before the tag was right.
	const publishNeeded = needsPublish({ mode, unpublishedCount: unpublished.length });
	const released = publishNeeded ? unpublished : packages;
	const linesFile = readLinesFile(git, 'HEAD');
	const tag = await decideDistTag({
		mode,
		line,
		lines,
		released,
		version,
		override: linesFile?.lines.find(({ branch }) => branch === line.branch)?.distTag,
	});
	const tags =
		mode === 'lerna-independent'
			? released.map((pkg) => `${pkg.name}@${pkg.version}`)
			: [`v${version ?? ''}`];
	await summary(
		publishNeeded
			? `#${pr.number}: publishing ${tags.join(', ')} with dist-tag ${tag}`
			: `#${pr.number}: ${tags.join(', ')} is already on the registry; publishing nothing, checking dist-tag ${tag}`,
	);
	if (options.dryRun) {
		return;
	}

	for (const name of tags) {
		await ensureTag(publishGh, name, sha);
	}

	if (publishNeeded) {
		const command = publishCommandFor(mode, tag, linesFile?.publishCommand);
		await retry(
			async (attempt) => {
				await summary(`publish attempt ${attempt}: ${command}`);
				runShell(command, git.cwd);
			},
			{ attempts: PUBLISH_ATTEMPTS, baseDelayMs: 30_000 },
		);
	}

	const verified: string[] = [];
	if (mode !== 'custom') {
		await retry(
			async () => {
				verified.length = 0;
				for (const pkg of packages) {
					const packument = await fetchPackument(pkg.name);
					if (!packument?.versions.includes(pkg.version)) {
						throw new Error(`${pkg.name}@${pkg.version} is not on the registry`);
					}
					if (released.includes(pkg) && packument.distTags[tag] !== pkg.version) {
						throw new Error(
							`${pkg.name}: ${tag} points at ${packument.distTags[tag] ?? 'nothing'}, not ${pkg.version}`,
						);
					}
					verified.push(`${pkg.name}@${pkg.version} (${tag})`);
				}
			},
			{ attempts: REGISTRY_VERIFY_ATTEMPTS, baseDelayMs: 10_000 },
		);
	}
	await summary(
		mode === 'custom'
			? 'published with the custom command; the registry was not checked'
			: `${publishNeeded ? 'published' : 'already published'} and verified:\n${verified.map((entry) => `- ${entry}`).join('\n')}`,
	);

	if (line.role === 'current') {
		await syncToDev(git, publishGh, sha);
	}

	if (version !== null && isFirstStableOfMajor(version, stableTagsBefore)) {
		const rules = JSON.parse(git.show('origin/dev', '.github/renovate.json') ?? '{}') as {
			packageRules?: { description?: string; matchBaseBranches?: string[] }[];
		};
		const stop = rules.packageRules?.find(({ description }) =>
			description?.startsWith('release-automation: lock file maintenance stopped'),
		);
		await ensureIssue(
			gh,
			rotationIssue({
				version,
				publishedAt: new Date(),
				verified,
				lockfileStop:
					stop?.matchBaseBranches === undefined
						? 'No previous line had lock file maintenance to stop.'
						: `Stopped on ${stop.matchBaseBranches.join(', ')} (in dev's renovate.json).`,
			}),
			[],
		);
	}
}

/**
 * @param packages - The public packages at the release commit
 * @returns The packages whose version is not on the registry yet
 * @throws {Error} For a package that was never published: npm accepts no
 *   trusted publisher for it, so a person publishes a placeholder first
 */
async function unpublishedPackages(
	packages: readonly PublicPackage[],
): Promise<PublicPackage[]> {
	const result: PublicPackage[] = [];
	for (const pkg of packages) {
		const packument = await fetchPackument(pkg.name);
		if (packument === null) {
			throw new Error(
				`${pkg.name} was never published. Publish a placeholder by hand and set its trusted publisher first`,
			);
		}
		if (!packument.versions.includes(pkg.version)) {
			result.push(pkg);
		}
	}
	return result;
}

/**
 * @param input - The release
 * @returns The dist-tag of the release
 */
async function decideDistTag(input: {
	readonly mode: PublishMode;
	readonly line: ClassifiedLine;
	readonly lines: readonly ClassifiedLine[];
	/** The packages the release is about: those published now, or all of them on a run that finds them already published. */
	readonly released: readonly PublicPackage[];
	readonly version: string | null;
	/** The dist-tag the line names in the lines file. */
	readonly override: string | undefined;
}): Promise<string> {
	const successorStablePublished = input.line.successorStable !== null;
	const versions =
		input.mode === 'lerna-independent'
			? input.released.map((pkg) => ({ version: pkg.version, name: pkg.name }))
			: [{ version: input.version ?? '', name: input.released[0]?.name ?? null }];
	const tags = new Set<string>();
	for (const { version, name } of versions) {
		const packument = name === null ? null : await fetchPackument(name);
		tags.add(
			distTag({
				version,
				role: input.line.role,
				independent: input.mode === 'lerna-independent',
				successorStablePublished,
				latestOnRegistry: packument?.distTags['latest'] ?? null,
				...(input.override === undefined ? {} : { override: input.override }),
			}),
		);
	}
	if (tags.size !== 1) {
		throw new Error(
			`The packages of one release need one dist-tag, not ${[...tags].join(', ')}`,
		);
	}
	return [...tags][0] ?? 'latest';
}

/**
 * @param mode - The publishing mode
 * @param tag - The dist-tag
 * @param override - The command of the lines file
 * @returns The publish command
 */
function publishCommandFor(
	mode: PublishMode,
	tag: string,
	override: string | undefined,
): string {
	if (override !== undefined) {
		return `DIST_TAG=${tag} ${override}`;
	}
	if (mode === 'npm-single') {
		return `npm publish --provenance --access public --tag ${tag}`;
	}
	if (mode === 'custom') {
		throw new Error('A repository without npm packages sets "publishCommand"');
	}
	return `yarn lerna publish from-package --dist-tag ${tag} --yes`;
}

/**
 * Creates a tag on the release commit, or checks that it already points there.
 * @param gh - The Publish App's client
 * @param name - The tag
 * @param sha - The release commit
 */
async function ensureTag(gh: GitHub, name: string, sha: string): Promise<void> {
	try {
		await gh.rest('POST', '/repos/{repo}/git/refs', { ref: `refs/tags/${name}`, sha });
	} catch (error) {
		if (!(error instanceof GitHubError) || error.status !== 422) {
			throw error;
		}
		const existing = await gh.rest<{ object: { sha: string } }>(
			'GET',
			`/repos/{repo}/git/ref/tags/${encodeURIComponent(name)}`,
		);
		if (existing.object.sha !== sha) {
			throw new Error(
				`Tag ${name} points at ${existing.object.sha}, not the release ${sha}`,
			);
		}
	}
}

/**
 * Brings a release on `main` back to `dev`: merges `main` into the head of
 * `dev`, runs the Minimum CI on the result through a `sync/<sha>` branch,
 * and moves `dev` to it without force. When `dev` moved meanwhile, it tries
 * again from the new head, three times in all.
 * @param git - Git access
 * @param gh - The Publish App's client
 * @param sha - The release commit on `main`
 */
async function syncToDev(git: LocalGit, gh: GitHub, sha: string): Promise<void> {
	const token = requireEnv('PUBLISH_APP_TOKEN');
	const slug = requireEnv('PUBLISH_APP_SLUG');
	const bot = await gh.rest<{ id: number }>(
		'GET',
		`/users/${encodeURIComponent(`${slug}[bot]`)}`,
	);
	const syncBranch = `sync/${sha.slice(0, 12)}`;
	await retry(
		async () => {
			git.raw('fetch', 'origin', 'dev');
			git.raw('checkout', '--force', '--detach', 'origin/dev');
			git.raw(
				'-c',
				`user.name=${slug}[bot]`,
				'-c',
				`user.email=${bot.id}+${slug}[bot]@users.noreply.github.com`,
				'merge',
				'--no-ff',
				'--no-edit',
				sha,
			);
			const merged = git.sha('HEAD');
			git.pushAs(token, gh.repository, `HEAD:refs/heads/${syncBranch}`);
			await waitForCheck(gh, merged, CI_OK);
			await gh.rest('PATCH', '/repos/{repo}/git/refs/heads/dev', {
				sha: merged,
				force: false,
			});
			await summary(`dev moved to ${merged}`);
		},
		{ attempts: 3, baseDelayMs: 5000 },
	);
	await gh.rest('DELETE', `/repos/{repo}/git/refs/heads/${syncBranch}`);
}

/**
 * Waits until a check on a commit concludes.
 * @param gh - The client
 * @param sha - The commit
 * @param name - The check
 * @throws {Error} When it fails or does not finish within an hour
 */
async function waitForCheck(gh: GitHub, sha: string, name: string): Promise<void> {
	const deadline = Date.now() + 60 * 60 * 1000;
	while (Date.now() < deadline) {
		const { check_runs } = await gh.rest<{
			check_runs: { status: string; conclusion: string | null }[];
		}>('GET', `/repos/{repo}/commits/${sha}/check-runs?check_name=${name}`);
		const run = check_runs[0];
		if (run?.status === 'completed') {
			if (run.conclusion === 'success') {
				return;
			}
			throw new Error(
				`${name} on ${sha} concluded ${run.conclusion ?? 'without a result'}`,
			);
		}
		await new Promise((resolve) => setTimeout(resolve, 30_000));
	}
	throw new Error(`${name} on ${sha} did not finish within an hour`);
}
