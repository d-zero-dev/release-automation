import type { Promotion } from '../next-version.js';

import { runShell } from '../io/exec.js';
import { fetchPackument } from '../io/npm.js';
import { publicPackages, publishModeAt } from '../io/repo.js';
import { releasePrOrigin } from '../pr-checks.js';
import { CURRENT_PUBLISH_BRANCH } from '../types.js';

import { classifiedLines, github, localGit, requireEnv, summary } from './context.js';
import { generateRelease } from './generate.js';
import { baselineOf, lineMarker, markerValue } from './release-pr.js';

/**
 * Normalizes the dates a changelog generator writes, so that a release
 * generated on another day compares equal.
 * @param text - A changelog
 * @returns The changelog with `YYYY-MM-DD` dates replaced
 * @example
 * normalizeDates('## 1.0.0 (2026-11-25)'); // '## 1.0.0 (DATE)'
 */
export function normalizeDates(text: string): string {
	return text.replaceAll(/\b\d{4}-\d{2}-\d{2}\b/g, 'DATE');
}

/**
 * Verifies that a pull request into a publish branch is a Release PR the
 * automation generated: the Release App wrote the commit on top of the
 * line's branch, the line's branch contains its parent, and generating the
 * release again from that parent gives the same files. Runs on
 * `pull_request_target`, so the checks of the target branch judge the pull
 * request, and no code of the pull request runs: the generation runs on the
 * parent, which the protected line branch already holds.
 * @param options - The pull request
 * @param options.pr - Its number
 * @throws {Error} When the pull request is not a valid Release PR
 * @example
 * await verifyReleasePrCommand({ pr: 12 });
 */
export async function verifyReleasePrCommand(options: {
	readonly pr: number;
}): Promise<void> {
	const git = localGit();
	const gh = github('GITHUB_TOKEN');
	const appSlug = requireEnv('RELEASE_APP_SLUG');
	const pr = await gh.rest<{
		user: { login: string };
		body: string | null;
		labels: { name: string }[];
		base: { ref: string };
		head: { sha: string };
	}>('GET', `/repos/{repo}/pulls/${options.pr}`);
	const { lines } = classifiedLines(git, new Date());
	const line = lines.find(
		(candidate) =>
			candidate.publishBranch === pr.base.ref &&
			(pr.body ?? '').includes(lineMarker(candidate.branch)),
	);
	if (line === undefined) {
		if (pr.base.ref !== CURRENT_PUBLISH_BRANCH) {
			// A line branch other than main also takes ordinary pull requests;
			// the publish step refuses to publish one that this check did not pass.
			await summary(`#${options.pr} is not a Release PR; nothing to verify`);
			return;
		}
		throw new Error(
			`#${options.pr} targets ${pr.base.ref} but is not a Release PR of a line that publishes there`,
		);
	}

	git.raw(
		'fetch',
		'origin',
		`+refs/pull/${options.pr}/head:refs/remotes/pr/${options.pr}`,
	);
	const head = git.sha(`pr/${options.pr}`);
	if (head !== pr.head.sha) {
		throw new Error(`#${options.pr} moved while it was verified; run again`);
	}
	const parent = git.sha(`${head}^1`);
	if (git.raw('rev-list', '--parents', '-n', '1', head).split(' ').length !== 2) {
		throw new Error('The release commit must have one parent');
	}
	if (!git.isAncestor(parent, `origin/${line.branch}`)) {
		throw new Error(`The release commit is not on top of ${line.branch}`);
	}

	const commit = await gh.rest<{ author: { login: string } | null }>(
		'GET',
		`/repos/{repo}/commits/${head}`,
	);
	const origin = releasePrOrigin(
		{
			author: pr.user.login,
			commits: [{ author: commit.author?.login ?? null, verified: true }],
			body: pr.body ?? '',
			labels: pr.labels.map(({ name }) => name),
		},
		`${appSlug}[bot]`,
	);
	if (!origin.ok) {
		throw new Error(
			`#${options.pr} was not generated by the Release App: ${origin.reasons.join('; ')}`,
		);
	}

	const promote = markerValue(pr.body, 'promote') as Promotion | null;
	const mode = publishModeAt(git, `origin/${line.branch}`);
	if (mode !== 'custom') {
		const never: string[] = [];
		for (const pkg of publicPackages(git, head)) {
			if ((await fetchPackument(pkg.name)) === null) {
				never.push(pkg.name);
			}
		}
		if (never.length > 0) {
			throw new Error(
				`Never published, so no trusted publisher can be set: ${never.join(', ')}. Publish a placeholder by hand and set its trusted publisher first`,
			);
		}
	}
	// On a local branch named like the line, not detached: `lerna version`
	// refuses a detached HEAD, and its `allowBranch` names the line's branch.
	git.raw('checkout', '--force', '-B', line.branch, parent);
	runShell('yarn install --immutable', git.cwd);
	const generated = generateRelease({
		git,
		mode,
		line,
		lines,
		baseline: baselineOf(git, line, mode),
		promote,
		now: new Date(),
	});
	if (!generated.ok) {
		throw new Error(`The release cannot be generated again: ${generated.reason}`);
	}
	git.raw('add', '--all');
	const changed = git
		.raw('diff', '--cached', '--name-only', head)
		.split('\n')
		.filter((file) => file !== '');
	const differing = changed.filter((file) => {
		const expected = git.show(head, file);
		const actual = git.raw('show', `:${file}`);
		return !(
			expected !== null &&
			file.endsWith('CHANGELOG.md') &&
			normalizeDates(expected) === normalizeDates(actual)
		);
	});
	if (differing.length > 0) {
		throw new Error(
			`#${options.pr} differs from a fresh generation in: ${differing.join(', ')}`,
		);
	}
	await summary(`#${options.pr}: a valid Release PR of ${line.branch}`);
}
